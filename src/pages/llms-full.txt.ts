// /llms-full.txt: the whole site as plain Markdown, for assistants that read one file instead of crawling.
import type { APIRoute } from "astro";
import {
  company,
  hero,
  allServices,
  core,
  solutionsIntro,
  whatWeDoIntro,
  howWeWork,
  technologies,
  testimonial,
  about,
  clientsIntro,
} from "../data/site";
import { clients } from "../data/clients";

export const GET: APIRoute = () => {
  const md = [
    `# ${company.name}: ${company.tagline}`,
    "",
    `> ${company.description}`,
    "",
    `- Razão social: ${company.legalName}`,
    `- CNPJ: ${company.cnpj}`,
    `- Site: ${company.url}`,
    `- WhatsApp: ${company.phoneDisplay}`,
    `- E-mail: ${company.email}`,
    ...company.social.map((s) => `- ${s.name}: ${s.url}`),
    "",
    `## ${hero.title}`,
    "",
    hero.subtitle,
    "",
    "## O que fazemos",
    "",
    whatWeDoIntro,
    "",
    `${core.title}. ${core.text}`,
    "",
    ...allServices.flatMap((s) => [
      `### ${s.name}`,
      "",
      `${s.pitch} ${s.short}`,
      "",
      ...s.features.map((f) => `- ${f}`),
      "",
    ]),
    "## Soluções",
    "",
    solutionsIntro,
    "",
    "## Como fazemos",
    "",
    ...howWeWork.intro,
    "",
    ...howWeWork.principles.map((p) => `- **${p.name}**: ${p.text}`),
    "",
    "## Tecnologias",
    "",
    technologies.intro,
    "",
    ...technologies.areas.map((a) => `- **${a.name}**: ${a.text}`),
    "",
    "## Quem somos",
    "",
    `${about.headline}. ${about.text}`,
    "",
    "### Nosso compromisso",
    "",
    ...about.commitments.map((c) => `- **${c.name}**: ${c.text}`),
    "",
    "### Valores",
    "",
    ...about.valuesIntro,
    "",
    ...about.values.map((v) => `- **${v.name}**: ${v.text}`),
    "",
    ...about.extras.map((e) => `- **${e.name}**: ${e.text}`),
    "",
    "## Clientes",
    "",
    clientsIntro,
    "",
    clients.map((c) => c.name).join(", ") + ".",
    "",
    `> "${testimonial.quote}" (${testimonial.author}, ${testimonial.client})`,
    "",
    "## Contato",
    "",
    `Envie seus dados em ${company.url}/contato que entraremos em contato com você, ou fale pelo WhatsApp ${company.phoneDisplay} e pelo e-mail ${company.email}.`,
    "",
  ];
  return new Response(md.join("\n"), { headers: { "Content-Type": "text/plain; charset=utf-8" } });
};
